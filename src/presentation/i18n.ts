const CATALOGS: Readonly<Record<SupportedLocale, PresentationCatalog>> = {
  en: ENGLISH_CATALOG,
  "zh-CN": CHINESE_CATALOG
};

export type PresentationParameter = string | number | boolean;
export type PresentationParameters = Readonly<Record<string, PresentationParameter>>;

export interface DateTimePresentationOptions {
  readonly timeZone?: string;
}

export interface LocalizedPresentation {
  readonly locale: SupportedLocale;
  message(
    key: PresentationMessageKey,
    parameters?: PresentationParameters
  ): string;
  number(value: number): string;
  dateTime(
    value: string | number | Date,
    options?: DateTimePresentationOptions
  ): string;
}

export class PresentationError extends Error {
  readonly code: string;

  constructor(code: string, message: string) {
    super(message);
    this.name = "PresentationError";
    this.code = code;
  }
}

export function resolveLocale(
  preferences: LocalePreferences = {}
): SupportedLocale {
  const candidates = [
    preferences.session,
    preferences.command,
    preferences.user,
    ...(preferences.detected ?? [])
  ];

  for (const candidate of candidates) {
    const locale = normalizeLocale(candidate);
    if (locale !== null) {
      return locale;
    }
  }

  return "en";
}

export function getPresentationCatalog(
  locale: SupportedLocale
): PresentationCatalog {
  return CATALOGS[locale];
}

export function createPresentation(
  locale: SupportedLocale
): LocalizedPresentation {
  const catalog = getPresentationCatalog(locale);
  const numberFormatter = new Intl.NumberFormat(locale);

  return {
    locale,
    message(key, parameters = {}) {
      if (!Object.hasOwn(ENGLISH_CATALOG, key)) {
        throw new PresentationError(
          "PRESENTATION_MESSAGE_UNKNOWN",
          `Unknown presentation message key: ${String(key)}`
        );
      }

      const template = catalog[key] ?? ENGLISH_CATALOG[key];
      return interpolate(template, parameters, key);
    },
    number(value) {
      return numberFormatter.format(value);
    },
    dateTime(value, options = {}) {
      const date = value instanceof Date ? value : new Date(value);
      if (Number.isNaN(date.getTime())) {
        throw new PresentationError(
          "PRESENTATION_DATE_INVALID",
          "The presentation date value is invalid."
        );
      }

      return new Intl.DateTimeFormat(locale, {
        dateStyle: "medium",
        timeStyle: "short",
        ...(options.timeZone === undefined
          ? {}
          : { timeZone: options.timeZone })
      }).format(date);
    }
  };
}

function normalizeLocale(value: unknown): SupportedLocale | null {
  if (typeof value !== "string") {
    return null;
  }

  const normalized = value.trim().replaceAll("_", "-").toLowerCase();
  if (normalized === "" || normalized === "auto") {
    return null;
  }
  if (normalized === "en" || normalized.startsWith("en-")) {
    return "en";
  }
  if (
    normalized === "zh" ||
    normalized === "zh-cn" ||
    normalized === "zh-hans" ||
    normalized.startsWith("zh-hans-") ||
    normalized === "zh-sg"
  ) {
    return "zh-CN";
  }

  return null;
}

function interpolate(
  template: string,
  parameters: PresentationParameters,
  key: PresentationMessageKey
): string {
  return template.replace(
    /\{([A-Za-z][A-Za-z0-9]*)\}/g,
    (_placeholder, parameterName: string) => {
      if (!Object.hasOwn(parameters, parameterName)) {
        throw new PresentationError(
          "PRESENTATION_PARAMETER_MISSING",
          `Missing presentation parameter '${parameterName}' for '${key}'.`
        );
      }

      return String(parameters[parameterName]);
    }
  );
}
